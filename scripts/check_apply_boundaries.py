"""Independent compact strict-stream integration fixtures; no oracle invocation."""
import argparse,bz2,hashlib,json,pathlib,re
from check_apply import integer,literal
ROOT=pathlib.Path(__file__).resolve().parents[1]
def stream_crc(raw):
    bits=''.join(f'{b:08b}' for b in raw)
    marker=f'{0x177245385090:048b}'
    pos=bits.rindex(marker)+48
    bits=bits[:pos]+('1' if bits[pos]=='0' else '0')+bits[pos+1:]
    return bytes(int(bits[i:i+8],2) for i in range(0,len(bits),8))
def fixtures():
    rows=[]
    for empty in (False,True):
        for index,stage in enumerate(('Control','Diff','Extra')):
            ctrl=b'' if empty else b''.join(integer(v) for v in ((1,0,0) if stage=='Diff' else (0,1,0)))
            plain=[ctrl,b'X' if stage=='Diff' and not empty else b'',b'X' if stage!='Diff' and not empty else b'']
            blocks=[bz2.compress(p,compresslevel=9) for p in plain]
            original=blocks[index]
            variants={'truncate':(original[:-1],'TruncatedData',None,len(original)-1),'combined-crc':(stream_crc(original),'DecompressionFailed','crc',None),'trailing':(original+b'!','InvalidField','trailing data after single bzip2 stream',len(original)),'concat':(original+original,'InvalidField','trailing data after single bzip2 stream',len(original))}
            if plain[index]:
                wrong=bytearray(original);wrong[10]^=1
                variants['block-crc']=(bytes(wrong),'DecompressionFailed','crc',None)
            for mutation,(raw,kind,field,relative) in variants.items():
                altered=blocks.copy();altered[index]=raw
                start=32+sum(len(b) for b in altered[:index])
                patch=b'BSDIFF40'+integer(len(altered[0]))+integer(len(altered[1]))+integer(0 if empty else 1)+b''.join(altered)
                rows.append(dict(id=f'{"empty" if empty else "output"}-{stage.lower()}-{mutation}',patch=patch,kind=kind,stage=stage,field=field,offset=None if relative is None else start+relative))
    return rows

def resource_payloads():
    def pack(ctrl,diff,extra):
        blocks=[bz2.compress(b,compresslevel=9) for b in (b''.join(integer(v) for t in ctrl for v in t),diff,extra)]
        return b'BSDIFF40'+integer(len(blocks[0]))+integer(len(blocks[1]))+integer(2)+b''.join(blocks)
    rows={'resource_patch':pack([(0,0,0),(1,1,0)],b'\0',b'X')}
    for kind in ('diff','extra'):
        for n in (2,3):
            raw=b'ABC'[:n]
            rows[f'resource_{kind}{n}']=pack([(2,0,0)] if kind=='diff' else [(0,2,0)],raw if kind=='diff' else b'',raw if kind=='extra' else b'')
    return rows

def resource_literals(generate=False):
    path=ROOT/'apply_resources_test.mbt'
    source=path.read_text()
    for name,raw in resource_payloads().items():
        pattern=r'fn '+name+r'\(\) -> Bytes \{[^}]*\}'
        if generate:
            source=re.sub(pattern,lambda m:'fn '+name+'() -> Bytes {\n'+literal(raw)+'\n}',source)
        section=source.split('fn '+name+'()',1)[1].split('}',1)[0]
        assert bytes(int(x,16) for x in re.findall(r'\\x([0-9a-f]{2})',section))==raw,name
    if generate:path.write_text(source,encoding='utf8',newline='\n')

def generate():
    source=['// Generated by scripts/check_apply_boundaries.py; independent Python bz2 streams.']
    manifest=[]
    for i,row in enumerate(fixtures()):
        source+=['','///|',f'fn boundary_patch_{i}() -> Bytes {{',literal(row['patch']),'}','','///|',f'test "apply-boundary-{row["id"]}" {{',f'  let patch = boundary_patch_{i}()', '  let snapshot = patch.to_array()',f'  match @moonbsdiff.apply(b"", patch, @moonbsdiff.Limits::for_apply()) {{','    Ok(_) => abort("strict patch accepted")','    Err(e) => {',f'      assert_eq(e.kind, {row["kind"]})',f'      assert_eq(e.stage, {row["stage"]})',f'      assert_eq(e.block, Some("{row["stage"].lower()}"))',f'      assert_eq(e.field, '+('None' if row['field'] is None else 'Some("'+row['field']+'")')+')',f'      assert_eq(e.offset, '+('None' if row['offset'] is None else f'Some({row["offset"]}L)')+')','    }','  }','  assert_eq(patch.to_array(), snapshot)','  assert_eq(@moonbsdiff.apply(b"", apply_fixture_0_patch(), @moonbsdiff.Limits::for_apply()), Ok(b""))','}']
        manifest.append({k:v for k,v in row.items() if k!='patch'}|dict(size=len(row['patch']),sha256=hashlib.sha256(row['patch']).hexdigest()))
    (ROOT/'apply_boundaries_test.mbt').write_text('\n'.join(source)+'\n',encoding='utf8',newline='\n')
    (ROOT/'testdata/apply/boundaries.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf8',newline='\n')
def verify():
    source=(ROOT/'apply_boundaries_test.mbt').read_text()
    manifest=json.loads((ROOT/'testdata/apply/boundaries.json').read_text())
    expected=[]
    for i,row in enumerate(fixtures()):
        section=source.split(f'fn boundary_patch_{i}()',1)[1].split('}',1)[0]
        assert bytes(int(x,16) for x in re.findall(r'\\x([0-9a-f]{2})',section))==row['patch']
        expected.append({k:v for k,v in row.items() if k!='patch'}|dict(size=len(row['patch']),sha256=hashlib.sha256(row['patch']).hexdigest()))
    assert manifest==expected
    assert source.count('test "apply-boundary-')==len(expected)
    print(f'{len(expected)} independent strict apply fixtures verified')
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--generate',action='store_true');args=parser.parse_args()
    if args.generate:generate()
    resource_literals(args.generate)
    verify()
